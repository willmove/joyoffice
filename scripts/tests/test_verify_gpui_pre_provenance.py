SPEC = importlib.util.spec_from_file_location(
    "verify_gpui_pre_provenance",
    pathlib.Path(__file__).resolve().parents[1] / "verify_gpui_pre_provenance.py",
)
provenance = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(provenance)

REV = "0123456789abcdef0123456789abcdef01234567"
LIB = b"pub fn demo() -> u32 { 7 }\n"
LICENSE = b"Apache License 2.0 (fake)\n"


def manifest(metadata=True, rev=REV, lib_path="src/lib.rs"):
    text = ('# generated by cargo\n[package]\nedition = "2024"\nname = "gpui-pre-demo"\nversion = "0.3.9"\n'
            'build = false\n')
    if metadata:
        text += f'\n[package.metadata.gpui-pre]\nzed-crate = "demo"\nzed-version = "0.1.0"\nzed-rev = "{rev}"\n'
    text += f'\n[lib]\nname = "demo"\npath = "{lib_path}"\n'
    return text.encode()


def package_files(**changes):
    files = {
        "Cargo.toml": manifest(),
        "Cargo.toml.orig": b'[package]\nname = "gpui-pre-demo"\nedition.workspace = true\n',
        "Cargo.lock": b"# generated by cargo package\nversion = 4\n",
        "LICENSE-APACHE": LICENSE,
        "README.md": b"# demo\n",
        "src/lib.rs": LIB,
    }
    for path, data in changes.items():
        if data is None:
            del files[path]
        else:
            files[path] = data
    return files


# Fake Zed checkout. LICENSE files are git symlinks in Zed; they are described
# separately so the tests need no filesystem symlinks (unavailable on some Windows hosts).
ZED_FILES = {
    "Cargo.toml": b'[workspace]\nmembers = [\n    "crates/demo",\n    "crates/demo/nested",\n]\n',
    "LICENSE-APACHE": LICENSE,
    "crates/demo/Cargo.toml": b'[package]\nname = "demo"\nversion = "0.1.0"\nedition.workspace = true\n',
    "crates/demo/README.md": b"# demo\n",
    "crates/demo/src/lib.rs": LIB,
    "crates/demo/nested/Cargo.toml": b'[package]\nname = "nested"\nversion = "0.1.0"\n',
    "crates/demo/nested/src/lib.rs": b"// another package\n",
    "tooling/fixture/demo/Cargo.toml": b'[package]\nname = "demo"\nversion = "0.0.0"\n',
}
ZED_SYMLINKS = {"crates/demo/LICENSE-APACHE": "../../LICENSE-APACHE"}


def write_files(root, files):
    for path, data in files.items():
        target = pathlib.Path(root, path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def read_files(root):
    return {path.relative_to(root).as_posix(): path.read_bytes()
            for path in sorted(pathlib.Path(root).rglob("*")) if path.is_file()}


class DirectoryTree:
    """ZedTree stand-in built from a fake checkout directory plus symlink entries."""

    def __init__(self, root, symlinks):
        self.entries, self.blobs, self.prefetched = {}, {}, []
        listing = [(path, data, "100644") for path, data in read_files(root).items()]
        listing += [(path, target.encode(), "120000") for path, target in symlinks.items()]
        for path, data, mode in listing:
            oid = provenance.blob_id(data)
            self.blobs[oid] = data
            self.entries[path] = (mode, "blob", oid)

    def prefetch(self, oids):
        self.prefetched.extend(oids)

    def read_blob(self, oid):
        return self.blobs[oid]


def crate_bytes(files, name="gpui-pre-demo", version="0.3.9"):
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
        for path, data in sorted(files.items()):
            info = tarfile.TarInfo(f"{name}-{version}/{path}")
            info.size = len(data)
            archive.addfile(info, io.BytesIO(data))
    return buffer.getvalue()


class FakeDirectories(unittest.TestCase):
    """Fake package and Zed directories on disk, compared without git or network."""

    def setUp(self):
        self.tmp = pathlib.Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        write_files(self.tmp / "zed", ZED_FILES)
        self.tree = DirectoryTree(self.tmp / "zed", ZED_SYMLINKS)
        self.members = provenance.workspace_members(self.tree)

    def check(self, files, deviations=None):
        write_files(self.tmp / "package", files)
        package = provenance.LockedPackage("gpui-pre-demo", "0.3.9", provenance.CRATES_IO, "0" * 64)
        report = provenance.PackageReport(package)
        report.files = read_files(self.tmp / "package")
        parsed = provenance.parse_toml(report.files["Cargo.toml"].decode())
        report.zed_crate, report.zed_rev, problems = provenance.zed_origin(parsed, package)
        report.problems += problems + provenance.check_build_inputs(parsed, report.files)
        if report.zed_crate:
            provenance.compare(report, self.tree, self.members, {} if deviations is None else deviations)
        return report

    def test_identical_package_passes(self):
        report = self.check(package_files())
        self.assertEqual(report.problems, [])
        self.assertEqual(report.zed_dir, "crates/demo")  # not tooling/fixture/demo, not a member
        self.assertEqual(report.identical, 3)
        self.assertEqual(report.symlinks, ["LICENSE-APACHE"])
        self.assertEqual(report.nested, ["nested"])
        self.assertEqual(report.ignored, ["Cargo.lock", "Cargo.toml", "Cargo.toml.orig"])

    def test_changed_content_fails(self):
        changed = b"pub fn demo() -> u32 { 8 }\n"
        report = self.check(package_files(**{"src/lib.rs": changed}))
        self.assertEqual(report.problems, [f"modified: src/lib.rs (sha256 {hashlib.sha256(changed).hexdigest()}, "
                                           f"zed_blob {provenance.blob_id(LIB)})"])

    def test_license_differing_from_symlink_target_fails(self):
        report = self.check(package_files(**{"LICENSE-APACHE": b"MIT\n"}))
        self.assertEqual(len(report.problems), 1)
        self.assertTrue(report.problems[0].startswith("modified: LICENSE-APACHE (sha256 "))

    def test_extra_file_fails(self):
        backdoor = b"// not in Zed\n"
        report = self.check(package_files(**{"src/backdoor.rs": backdoor, "vendor/lib.rs": LIB}))
        self.assertEqual(report.problems, [
            f"extra: src/backdoor.rs (sha256 {hashlib.sha256(backdoor).hexdigest()})",
            f"extra: vendor/lib.rs (sha256 {hashlib.sha256(LIB).hexdigest()}, same as Zed crates/demo/src/lib.rs)"])

    def test_missing_file_fails(self):
        report = self.check(package_files(**{"README.md": None}))
        self.assertEqual(report.problems, ["missing: README.md"])

    def test_nested_package_files_shipped_in_the_crate_fail(self):
        report = self.check(package_files(**{"nested/src/lib.rs": b"// another package\n"}))
        self.assertEqual(len(report.problems), 1)
        self.assertTrue(report.problems[0].startswith("extra: nested/src/lib.rs (sha256 "))

    def test_missing_metadata_fails(self):
        report = self.check(package_files(**{"Cargo.toml": manifest(metadata=False)}))
        self.assertEqual(report.problems, ["Cargo.toml has no [package.metadata.gpui-pre]"])
        self.assertIsNone(report.zed_dir)

    def test_abbreviated_rev_fails(self):
        report = self.check(package_files(**{"Cargo.toml": manifest(rev="0123456")}))
        self.assertEqual(report.problems, ["zed-rev missing or not a full commit id: '0123456'"])

    def test_target_pointing_at_unverified_file_fails(self):
        report = self.check(package_files(**{"Cargo.toml": manifest(lib_path="Cargo.toml.orig")}))
        self.assertEqual(report.problems, ["[lib] path = 'Cargo.toml.orig' is not a file compared with Zed"])

    def test_reviewed_deviations_are_pinned_to_content(self):
        changed = b"pub fn demo() -> u32 { 8 }\n"
        extra = b"// vendored copy\n"
        reviewed = {
            ("gpui-pre-demo", "0.3.9", "src/lib.rs"): {
                "kind": "modified", "path": "src/lib.rs", "reason": "test",
                "sha256": hashlib.sha256(changed).hexdigest(), "zed_blob": provenance.blob_id(LIB)},
            ("gpui-pre-demo", "0.3.9", "vendor/lib.rs"): {
                "kind": "copied", "path": "vendor/lib.rs", "reason": "test", "zed_path": "crates/demo/src/lib.rs"},
            ("gpui-pre-demo", "0.3.9", "src/added.rs"): {
                "kind": "added", "path": "src/added.rs", "reason": "test",
                "sha256": hashlib.sha256(extra).hexdigest()},
        }
        accepted = self.check(package_files(**{"src/lib.rs": changed, "vendor/lib.rs": LIB,
                                               "src/added.rs": extra}), dict(reviewed))
        self.assertEqual(accepted.problems, [])
        self.assertEqual(len(accepted.reviewed), 3)
        refused = self.check(package_files(**{"src/lib.rs": changed + b"//\n", "vendor/lib.rs": extra,
                                              "src/added.rs": extra}), dict(reviewed))
        self.assertEqual(len(refused.problems), 2)
        self.assertTrue(refused.problems[0].startswith("modified: src/lib.rs (reviewed deviation refused: content"))
        self.assertTrue(refused.problems[1].startswith("extra: vendor/lib.rs (reviewed deviation refused: content"))

    def test_only_needed_blobs_are_prefetched(self):
        self.tree.prefetched = []
        provenance.prefetch_crates(self.tree, self.members, {"demo"})
        wanted = {self.tree.entries[path][2] for path in ("crates/demo/Cargo.toml", "crates/demo/LICENSE-APACHE")}
        self.assertEqual(set(self.tree.prefetched), wanted)


class ArchiveAndManifestTests(unittest.TestCase):
    def test_crate_archive_round_trip(self):
        files = package_files()
        self.assertEqual(provenance.read_crate_archive(crate_bytes(files), "gpui-pre-demo", "0.3.9"), files)

    def test_unsafe_archive_entries_are_rejected(self):
        for name in ("other-0.1.0/src/lib.rs", "gpui-pre-demo-0.3.9/../x.rs", "gpui-pre-demo-0.3.9/a/./b"):
            buffer = io.BytesIO()
            with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
                info = tarfile.TarInfo(name)
                archive.addfile(info, io.BytesIO(b""))
            with self.assertRaises(ValueError, msg=name):
                provenance.read_crate_archive(buffer.getvalue(), "gpui-pre-demo", "0.3.9")
        buffer = io.BytesIO()
        with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
            link = tarfile.TarInfo("gpui-pre-demo-0.3.9/src/lib.rs")
            link.type, link.linkname = tarfile.SYMTYPE, "/etc/passwd"
            archive.addfile(link)
        with self.assertRaisesRegex(ValueError, "not a regular file"):
            provenance.read_crate_archive(buffer.getvalue(), "gpui-pre-demo", "0.3.9")

    def test_lock_selection(self):
        lock = ('version = 4\n\n[[package]]\nname = "gpui"\nversion = "0.2.2"\n\n'
                '[[package]]\nname = "gpui-pre-demo"\nversion = "0.3.9"\n'
                f'source = "{provenance.CRATES_IO}"\nchecksum = "{"a" * 64}"\n'
                'dependencies = [\n "gpui-pre",\n]\n\n'
                '[[package]]\nname = "gpui-pre"\nversion = "0.3.9"\n\n'
                '[[package]]\nname = "gpui-prelude"\nversion = "1.0.0"\n')
        names = [package.name for package in provenance.locked_packages(lock)]
        self.assertEqual(names, ["gpui-pre", "gpui-pre-demo"])

    def test_build_scripts_and_target_arrays(self):
        parsed = provenance.parse_toml('[package]\nname = "x"\nbuild = "build.rs"\n\n'
                                       '[[bench]]\nname = "a"\npath = "benches/a.rs"\n\n'
                                       '[[bench]]\nname = "b"\npath = "Cargo.lock"\n')
        files = {"Cargo.toml": b"", "Cargo.lock": b"", "build.rs": b"", "benches/a.rs": b""}
        self.assertEqual(provenance.check_build_inputs(parsed, files),
                         ["[bench] path = 'Cargo.lock' is not a file compared with Zed"])


class TomlSubsetTests(unittest.TestCase):
    SAMPLE = '''# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO
[package]
name = "gpui-pre-platform"
description = "Zed's `gpui_platform` crate \\"snapshot\\" \\u00e9"
readme = false
autolib = false
license = 'Apache-2.0'
long = """
first \\
    second"""
raw = \'\'\'C:\\path\'\'\'

[package.metadata.gpui-pre]
zed-crate = "gpui_platform"

[features]
default = ["multithreaded"]
screen-capture = [
    "gpui/screen-capture", # trailing comment
    "gpui_macos/screen-capture",
]

[lib]
name = "gpui_platform"
path = "src/gpui_platform.rs"

[[bench]]
name = "inspector_render"
harness = false

[[bench]]
name = "randomized_element_tree"

[target.'cfg(target_os = "macos")'.dependencies.gpui_macos]
version = "=0.3.9"
default-features = false

[lints.clippy.style]
level = "allow"
priority = -1

[dependencies]
syn = { version = "2", features = ["full"], default-features = true }
edition.workspace = true
'''

    def test_subset_parser_reads_cargo_manifests(self):
        parsed = provenance.TomlSubsetParser(self.SAMPLE).parse()
        self.assertEqual(parsed["package"]["description"], 'Zed\'s `gpui_platform` crate "snapshot" \u00e9')
        self.assertEqual(parsed["package"]["long"], "first second")
        self.assertEqual(parsed["package"]["raw"], "C:\\path")
        self.assertIs(parsed["package"]["readme"], False)
        self.assertEqual(parsed["package"]["metadata"]["gpui-pre"]["zed-crate"], "gpui_platform")
        self.assertEqual(parsed["features"]["screen-capture"][1], "gpui_macos/screen-capture")
        self.assertEqual([bench["name"] for bench in parsed["bench"]],
                         ["inspector_render", "randomized_element_tree"])
        self.assertEqual(parsed["target"]['cfg(target_os = "macos")']["dependencies"]["gpui_macos"]["version"],
                         "=0.3.9")
        self.assertEqual(parsed["lints"]["clippy"]["style"]["priority"], -1)
        self.assertEqual(parsed["dependencies"]["syn"]["features"], ["full"])
        self.assertEqual(parsed["dependencies"]["edition"], {"workspace": True})
        if provenance.tomllib is not None:
            self.assertEqual(parsed, provenance.tomllib.loads(self.SAMPLE))

    def test_subset_parser_refuses_what_it_does_not_understand(self):
        for text in ('a = 1.5\n', 'a = 1979-05-27\n', 'a = 1\na = 2\n', '[a]\n[a]\n', 'a = "open\n',
                     'a = 0x1f\n', 'a = "x" b = 1\n', 'a = "\\q"\n'):
            with self.assertRaises(ValueError, msg=text):
                provenance.TomlSubsetParser(text).parse()


def git_available():
    return shutil.which("git") is not None


@unittest.skipUnless(git_available(), "git is required for the end-to-end check")
class EndToEndTests(unittest.TestCase):
    """main() with a fake Cargo cache and a local Zed repository fetched over file://."""

    def setUp(self):
        self.tmp = pathlib.Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        zed = self.tmp / "zed"
        write_files(zed, ZED_FILES)
        self.git(zed, "init", "--quiet", "--initial-branch=main")
        self.git(zed, "add", "--all")
        for path, target in ZED_SYMLINKS.items():
            oid = self.git(zed, "hash-object", "-w", "--stdin", input=target.encode()).strip().decode()
            self.git(zed, "update-index", "--add", "--cacheinfo", f"120000,{oid},{path}")
        self.commit(zed, "fake zed")
        self.git(zed, "config", "uploadpack.allowFilter", "true")
        self.git(zed, "config", "uploadpack.allowAnySHA1InWant", "true")
        self.rev = self.git(zed, "rev-parse", "HEAD").strip().decode()
        self.remote = zed.as_uri()

    def commit(self, repo, message):
        self.git(repo, "-c", "user.name=test", "-c", "user.email=test@example.invalid",
                 "commit", "--quiet", "-m", message)

    def git(self, repo, *args, input=None):
        return subprocess.run(["git", "-c", "core.autocrlf=false", "-C", str(repo), *args],
                              input=input, capture_output=True, check=True).stdout

    def run_main(self, files, *extra, checksum=None):
        data = crate_bytes(files)
        cache = self.tmp / "cargo" / "registry" / "cache" / "index.crates.io-test"
        cache.mkdir(parents=True, exist_ok=True)
        (cache / "gpui-pre-demo-0.3.9.crate").write_bytes(data)
        lock = self.tmp / "Cargo.lock"
        lock.write_text(f'version = 4\n\n[[package]]\nname = "gpui-pre-demo"\nversion = "0.3.9"\n'
                        f'source = "{provenance.CRATES_IO}"\n'
                        f'checksum = "{checksum or hashlib.sha256(data).hexdigest()}"\n\n'
                        '[[package]]\nname = "serde"\nversion = "1.0.0"\n', encoding="utf-8")
        output = io.StringIO()
        with contextlib.redirect_stdout(output), contextlib.redirect_stderr(output):
            status = provenance.main(["--lockfile", str(lock), "--cargo-home", str(self.tmp / "cargo"),
                                      "--no-download", *extra])
        return status, output.getvalue()

    def fetch_args(self):
        return ["--zed-remote", self.remote, "--work-dir", str(self.tmp / "work")]

    def test_identical_package_passes_over_partial_fetch(self):
        files = package_files(**{"Cargo.toml": manifest(rev=self.rev)})
        status, output = self.run_main(files, *self.fetch_args(), "--expected-zed-rev", self.rev)
        self.assertEqual(status, 0, output)
        self.assertIn("ok       gpui-pre-demo 0.3.9 = crates/demo: 3 files identical", output)
        self.assertIn("Result: OK, 1 identical, 0 accepted with reviewed deviations, 0 failed", output)

    def test_commit_outside_the_zed_branch_fails(self):
        # A fork-only commit can be fetched through the upstream URL on GitHub.
        zed = self.tmp / "zed"
        self.git(zed, "checkout", "--quiet", "-b", "fork")
        (zed / "crates/demo/src/lib.rs").write_bytes(b"fn evil() {}\n")
        self.git(zed, "add", "crates/demo/src/lib.rs")
        self.commit(zed, "fork")
        fork = self.git(zed, "rev-parse", "HEAD").strip().decode()
        self.git(zed, "checkout", "--quiet", "main")
        files = package_files(**{"Cargo.toml": manifest(rev=fork), "src/lib.rs": b"fn evil() {}\n"})
        for extra in (self.fetch_args(), ["--zed-repo", str(zed)]):
            status, output = self.run_main(files, *extra)
            self.assertEqual(status, 1, output)
            self.assertIn(f"Zed commit {fork} is not in the history of", output)
            self.assertIn("ok       gpui-pre-demo 0.3.9 = crates/demo: 3 files identical", output)

    def test_changed_package_fails(self):
        files = package_files(**{"Cargo.toml": manifest(rev=self.rev), "src/lib.rs": b"fn evil() {}\n"})
        status, output = self.run_main(files, "--zed-repo", str(self.tmp / "zed"))
        self.assertEqual(status, 1, output)
        self.assertIn("modified: src/lib.rs", output)

    def test_missing_metadata_fails_without_fetching(self):
        status, output = self.run_main(package_files(**{"Cargo.toml": manifest(metadata=False)}),
                                       "--zed-remote", "file:///nonexistent")
        self.assertEqual(status, 1, output)
        self.assertIn("Cargo.toml has no [package.metadata.gpui-pre]", output)

    def test_checksum_mismatch_fails(self):
        files = package_files(**{"Cargo.toml": manifest(rev=self.rev)})
        status, output = self.run_main(files, "--zed-repo", str(self.tmp / "zed"), checksum="f" * 64)
        self.assertEqual(status, 1, output)
        self.assertIn("checksum differs from Cargo.lock", output)

    def test_reviewed_deviation_must_match_its_difference(self):
        reviewed = self.tmp / "reviewed.json"
        reviewed.write_text(json.dumps({"deviations": [{
            "package": "gpui-pre-demo", "version": "0.3.9", "path": "src/lib.rs", "kind": "added",
            "sha256": "0" * 64, "reason": "stale"}]}), encoding="utf-8")
        modified = package_files(**{"Cargo.toml": manifest(rev=self.rev), "src/lib.rs": b"fn evil() {}\n"})
        status, output = self.run_main(modified, "--zed-repo", str(self.tmp / "zed"),
                                       "--reviewed-deviations", str(reviewed))
        self.assertEqual(status, 1, output)
        self.assertIn("reviewed as added but is modified", output)
        identical = package_files(**{"Cargo.toml": manifest(rev=self.rev)})
        status, output = self.run_main(identical, "--zed-repo", str(self.tmp / "zed"),
                                       "--reviewed-deviations", str(reviewed))
        self.assertEqual(status, 1, output)
        self.assertIn("reviewed deviation matched nothing: gpui-pre-demo 0.3.9 src/lib.rs", output)
        self.assertIn("Result: FAILED", output)
        reviewed.write_text(json.dumps({"deviations": [{
            "package": "gpui-pre-demo", "version": "0.3.9", "path": "src/lib.rs", "kind": "added",
            "sha256": "0" * 64, "reason": "typo", "sha265": "0"}]}), encoding="utf-8")
        status, output = self.run_main(identical, "--zed-repo", str(self.tmp / "zed"),
                                       "--reviewed-deviations", str(reviewed))
        self.assertEqual(status, 2, output)

    def test_unknown_commit_cannot_run(self):
        files = package_files(**{"Cargo.toml": manifest(rev="f" * 40)})
        status, output = self.run_main(files, "--zed-repo", str(self.tmp / "zed"))
        self.assertEqual(status, 2, output)


