def load_deviations(path):
    """{(package, version, path): entry} from a reviewed-deviations JSON file."""
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise CheckError(f"{path}: {error}")
    if not isinstance(document, dict) or set(document) - {"note", "deviations"} \
            or not isinstance(document.get("deviations"), list):
        raise CheckError(f"{path}: expected an object with a 'deviations' list")
    deviations = {}
    for index, entry in enumerate(document["deviations"]):
        kind = entry.get("kind") if isinstance(entry, dict) else None
        required = {"package", "version", "path", "kind", "reason"} | DEVIATION_FIELDS.get(kind, set())
        if kind not in DEVIATION_FIELDS or set(entry) != required \
                or not all(isinstance(value, str) and value for value in entry.values()):
            raise CheckError(f"{path}: deviation {index} needs exactly the string fields {sorted(required)}")
        key = (entry["package"], entry["version"], entry["path"])
        if key in deviations:
            raise CheckError(f"{path}: duplicate deviation for {' '.join(key)}")
        deviations[key] = entry
    return deviations


def check_deviation(entry, found, data, oid, tree):
    """None if the reviewed entry accepts exactly this difference, else the reason it does not."""
    expected = {"modified": "modified", "added": "extra", "copied": "extra"}[entry["kind"]]
    if found != expected:
        return f"reviewed as {entry['kind']} but is {found}"
    if entry["kind"] == "modified" and oid != entry["zed_blob"]:
        return f"Zed blob is {oid}, reviewed against {entry['zed_blob']}"
    if entry["kind"] in ("modified", "added") and sha256(data) != entry["sha256"]:
        return f"content sha256 {sha256(data)} differs from the reviewed {entry['sha256']}"
    if entry["kind"] == "copied":
        try:
            source = resolve(tree, entry["zed_path"])
        except ValueError as error:
            return str(error)
        if blob_id(data) != source:
            return f"content differs from Zed {entry['zed_path']}"
    return None


def pin_hint(found, data, oid, tree):
    """What a reviewer needs to pin the difference in a reviewed-deviations file."""
    if found == "modified":
        return f" (sha256 {sha256(data)}, zed_blob {oid})"
    if found == "extra":
        own = blob_id(data)
        copies = sorted(path for path, (mode, kind, other) in tree.entries.items()
                        if other == own and mode != "120000")
        return f" (sha256 {sha256(data)}" + (f", same as Zed {copies[0]})" if copies else ")")
    return ""


def compare(report, tree, members, deviations):
    try:
        report.zed_dir = find_crate_dir(tree, members, report.zed_crate)
    except ValueError as error:
        report.problems.append(str(error))
        return
    upstream = upstream_files(tree, report.zed_dir, report)
    package = report.package
    for rel in sorted(set(report.files) | set(upstream)):
        if rel in PACKAGING_FILES:
            if rel in report.files:
                report.ignored.append(rel)
            continue
        data, oid = report.files.get(rel), upstream.get(rel)
        if data is not None and oid is not None and blob_id(data) == oid:
            report.identical += 1
            continue
        found = "missing" if data is None else "extra" if oid is None else "modified"
        entry = deviations.pop((package.name, package.version, rel), None)
        if entry is None:
            report.problems.append(f"{found}: {rel}{pin_hint(found, data, oid, tree)}")
            continue
        refused = check_deviation(entry, found, data, oid, tree)
        if refused:
            report.problems.append(f"{found}: {rel} (reviewed deviation refused: {refused})")
        else:
            report.reviewed.append(f"{entry['kind']}: {rel} - {entry['reason']}")


