#!/usr/bin/env python3
"""Verify every gpui-pre* crate against its pinned source, file by file.

The gpui-pre crates on crates.io are snapshots of zed-industries/zed published
by an individual, without .cargo_vcs_info.json. Each one names its origin in
[package.metadata.gpui-pre] (zed-crate, zed-rev). For every gpui-pre and
gpui-pre-* entry in Cargo.lock this script

1. takes the .crate archive from the Cargo cache, or downloads it from
   crates.io, and requires its SHA-256 to equal the Cargo.lock checksum, so the
   files are exactly the ones Cargo builds;
2. fetches the declared Zed commit with trees only (git fetch --depth=1
   --filter=blob:none), requires it to be an ancestor of Zed's main branch
   (GitHub also serves commits that exist only in forks of a repository) and
   finds the directory of the declared crate among the workspace members;
3. compares every file by git blob id with the file at the same path in that
   directory. The commit id authenticates its trees and their blob ids, so a
   matching blob id means byte-identical content without downloading blobs.

Any modified, extra or missing file fails (exit 1) unless it is a packaging
difference listed in PACKAGING_FILES / UPSTREAM_RULES, or an entry of a
--reviewed-deviations file pinned to its exact content. Exit 2 means the check
could not run (network, git, unreadable input).

Explicitly registered renamed registry crates are compared with a separately
checksum-pinned reference archive; they cannot bypass source comparison.
"""
