def sha256(data):
    return hashlib.sha256(data).hexdigest()


def blob_id(data):
    """Git object id of a blob with this content."""
    return hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest()


# --- TOML ---------------------------------------------------------------------

class TomlSubsetParser:
    """TOML reader for Pythons without tomllib, limited to what Cargo files use.

    Tables, arrays of tables, dotted and quoted keys, the four string forms,
    decimal integers, booleans, arrays and inline tables. Anything else
    (floats, dates, other number bases) raises ValueError instead of guessing.
    """
    BARE_KEY = re.compile(r"[A-Za-z0-9_-]+")
    INTEGER = re.compile(r"[+-]?(?:0|[1-9](?:_?[0-9])*)")
    DELIMITERS = " \t\r\n,]}#"
    ESCAPES = {"b": "\b", "t": "\t", "n": "\n", "f": "\f", "r": "\r", '"': '"', "\\": "\\"}

    def __init__(self, text):
        self.text = text
        self.pos = 0
        self.defined = set()

    def error(self, message):
        return ValueError(f"TOML line {self.text.count(chr(10), 0, self.pos) + 1}: {message}")

    def peek(self):
        return self.text[self.pos] if self.pos < len(self.text) else ""

    def parse(self):
        root = current = {}
        while True:
            self.skip_blank()
            if self.pos >= len(self.text):
                return root
            if self.text.startswith("[[", self.pos):
                self.pos += 2
                keys = self.parse_key()
                self.expect("]]")
                parent = self.walk(root, keys[:-1])
                array = parent.setdefault(keys[-1], [])
                if not isinstance(array, list):
                    raise self.error(f"{'.'.join(keys)} is not an array of tables")
                current = {}
                array.append(current)
            elif self.peek() == "[":
                self.pos += 1
                keys = self.parse_key()
                self.expect("]")
                current = self.walk(root, keys)
                if id(current) in self.defined:
                    raise self.error(f"table {'.'.join(keys)} defined twice")
                self.defined.add(id(current))
            else:
                keys = self.parse_key()
                self.expect("=")
                self.assign(current, keys, self.parse_value())
            self.end_line()

    def walk(self, table, keys):
        for key in keys:
            value = table.setdefault(key, {})
            if isinstance(value, list):
                value = value[-1] if value else None
            if not isinstance(value, dict):
                raise self.error(f"{key} is not a table")
            table = value
        return table

    def assign(self, table, keys, value):
        table = self.walk(table, keys[:-1])
        if keys[-1] in table:
            raise self.error(f"duplicate key {'.'.join(keys)}")
        table[keys[-1]] = value

    def skip_space(self):
        while self.peek() in (" ", "\t"):
            self.pos += 1

    def skip_blank(self):
        """Whitespace, newlines and comments (between statements and array items)."""
        while True:
            ch = self.peek()
            if ch in (" ", "\t", "\r", "\n"):
                self.pos += 1
            elif ch == "#":
                end = self.text.find("\n", self.pos)
                self.pos = len(self.text) if end < 0 else end
            else:
                return

    def end_line(self):
        self.skip_space()
        if self.peek() == "#":
            end = self.text.find("\n", self.pos)
            self.pos = len(self.text) if end < 0 else end
        if self.text.startswith("\r\n", self.pos):
            self.pos += 2
        elif self.peek() == "\n":
            self.pos += 1
        elif self.pos < len(self.text):
            raise self.error("expected end of line")

    def expect(self, token):
        self.skip_space()
        if not self.text.startswith(token, self.pos):
            raise self.error(f"expected {token!r}")
        self.pos += len(token)

    def parse_key(self):
        keys = []
        while True:
            self.skip_space()
            if self.peek() == '"':
                keys.append(self.parse_basic_string())
            elif self.peek() == "'":
                keys.append(self.parse_literal_string())
            else:
                match = self.BARE_KEY.match(self.text, self.pos)
                if not match:
                    raise self.error("expected a key")
                keys.append(match.group())
                self.pos = match.end()
            self.skip_space()
            if self.peek() != ".":
                return keys
            self.pos += 1

    def parse_value(self):
        self.skip_space()
        text, pos = self.text, self.pos
        if text.startswith('"""', pos):
            return self.parse_multiline('"')
        if text.startswith("'''", pos):
            return self.parse_multiline("'")
        ch = self.peek()
        if ch == '"':
            return self.parse_basic_string()
        if ch == "'":
            return self.parse_literal_string()
        if ch == "[":
            return self.parse_array()
        if ch == "{":
            return self.parse_inline_table()
        for word, value in (("true", True), ("false", False)):
            if text.startswith(word, pos) and self.delimited(pos + len(word)):
                self.pos += len(word)
                return value
        match = self.INTEGER.match(text, pos)
        if match and self.delimited(match.end()):
            self.pos = match.end()
            return int(match.group().replace("_", ""))
        raise self.error("unsupported value")

    def delimited(self, pos):
        return pos >= len(self.text) or self.text[pos] in self.DELIMITERS

    def check_char(self, ch):
        if (ch < " " and ch != "\t") or ch == "\x7f":
            raise self.error("control character in string")

    def parse_escape(self):
        code = self.text[self.pos + 1:self.pos + 2]
        if code in self.ESCAPES:
            self.pos += 2
            return self.ESCAPES[code]
        width = {"u": 4, "U": 8}.get(code)
        digits = self.text[self.pos + 2:self.pos + 2 + width] if width else ""
        if not width or not re.fullmatch(r"[0-9A-Fa-f]+", digits) or len(digits) != width:
            raise self.error("invalid escape")
        value = int(digits, 16)
        if value > 0x10FFFF or 0xD800 <= value <= 0xDFFF:
            raise self.error("invalid unicode escape")
        self.pos += 2 + width
        return chr(value)

    def parse_basic_string(self):
        self.pos += 1
        out = []
        while True:
            ch = self.peek()
            if ch == '"':
                self.pos += 1
                return "".join(out)
            if ch == "\\":
                out.append(self.parse_escape())
                continue
            if ch in ("", "\r", "\n"):
                raise self.error("unterminated string")
            self.check_char(ch)
            out.append(ch)
            self.pos += 1

    def parse_literal_string(self):
        end = self.text.find("'", self.pos + 1)
        line_end = self.text.find("\n", self.pos + 1)
        if end < 0 or 0 <= line_end < end:
            raise self.error("unterminated string")
        value = self.text[self.pos + 1:end]
        for ch in value:
            self.check_char(ch)
        self.pos = end + 1
        return value

    def parse_multiline(self, quote):
        self.pos += 3
        if self.text.startswith("\r\n", self.pos):
            self.pos += 2
        elif self.peek() == "\n":
            self.pos += 1
        out = []
        while True:
            if self.text.startswith(quote * 3, self.pos):
                run = len(self.text[self.pos:]) - len(self.text[self.pos:].lstrip(quote))
                if run > 5:
                    raise self.error("too many quotes")
                out.append(quote * (run - 3))
                self.pos += run
                return "".join(out)
            ch = self.peek()
            if ch == "":
                raise self.error("unterminated string")
            if quote == '"' and ch == "\\":
                rest = self.text[self.pos + 1:]
                stripped = rest.lstrip(" \t")
                if stripped.startswith(("\n", "\r\n")):
                    self.pos = len(self.text) - len(stripped.lstrip(" \t\r\n"))
                else:
                    out.append(self.parse_escape())
                continue
            if self.text.startswith("\r\n", self.pos):
                out.append("\n")
                self.pos += 2
                continue
            if ch != "\n":
                self.check_char(ch)
            out.append(ch)
            self.pos += 1

    def parse_array(self):
        self.pos += 1
        items = []
        while True:
            self.skip_blank()
            if self.peek() == "]":
                self.pos += 1
                return items
            items.append(self.parse_value())
            self.skip_blank()
            if self.peek() == ",":
                self.pos += 1
            elif self.peek() == "]":
                self.pos += 1
                return items
            else:
                raise self.error("expected ',' or ']'")

    def parse_inline_table(self):
        self.pos += 1
        table = {}
        self.skip_space()
        if self.peek() == "}":
            self.pos += 1
            return table
        while True:
            keys = self.parse_key()
            self.expect("=")
            self.assign(table, keys, self.parse_value())
            self.skip_space()
            if self.peek() == ",":
                self.pos += 1
            elif self.peek() == "}":
                self.pos += 1
                return table
            else:
                raise self.error("expected ',' or '}'")


def parse_toml(text):
    if tomllib is not None:
        return tomllib.loads(text)
    return TomlSubsetParser(text).parse()


# --- Cargo side ---------------------------------------------------------------

def locked_packages(lock_text):
    """gpui-pre and gpui-pre-* entries of a Cargo.lock, sorted by name and version."""
    packages = []
    for entry in parse_toml(lock_text).get("package", []):
        name = entry.get("name", "")
        if name == PACKAGE_PREFIX or name.startswith(PACKAGE_PREFIX + "-"):
            packages.append(LockedPackage(name, entry.get("version"), entry.get("source"),
                                          entry.get("checksum")))
    return sorted(packages)


def read_crate_archive(data, name, version):
    """Regular files of a .crate (tar.gz) as {relative path: bytes}; rejects anything unusual."""
    prefix = f"{name}-{version}/"
    files = {}
    unpacked = 0
    try:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
            for member in archive:
                if not (member.name + "/").startswith(prefix):
                    raise ValueError(f"entry outside {prefix}: {member.name}")
                rel = member.name[len(prefix):].rstrip("/")
                if member.isdir():
                    continue
                if rel in ("", ".", "..") or rel != posixpath.normpath(rel) or rel.startswith(("/", "../")):
                    raise ValueError(f"unsafe entry path: {member.name}")
                if not member.isfile():
                    raise ValueError(f"not a regular file: {member.name}")
                if rel in files:
                    raise ValueError(f"duplicate entry: {member.name}")
                unpacked += member.size
                if unpacked > MAX_UNPACKED_BYTES:
                    raise ValueError("unpacked size over limit")
                files[rel] = archive.extractfile(member).read()
    except (tarfile.TarError, EOFError, OSError) as error:
        raise ValueError(f"unreadable archive: {error}")
    return files


def crate_archive(package, cargo_home, download, notes):
    """The .crate bytes whose SHA-256 equals the Cargo.lock checksum, or None."""
    filename = f"{package.name}-{package.version}.crate"
    for candidate in sorted((cargo_home / "registry" / "cache").glob(f"*/{filename}")):
        data = candidate.read_bytes()
        if sha256(data) == package.checksum:
            return data
        notes.append(f"skipped {candidate}: checksum differs from Cargo.lock")
    if not download:
        notes.append(f"{filename} not in {cargo_home}/registry/cache and downloads are disabled")
        return None
    url = CRATE_URL.format(name=package.name, version=package.version)
    request = urllib.request.Request(url, headers={"User-Agent": "joyoffice-verify-gpui-pre-provenance"})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            data = response.read(MAX_CRATE_BYTES + 1)
    except (urllib.error.URLError, OSError) as error:
        raise CheckError(f"download {url}: {error}")
    if len(data) > MAX_CRATE_BYTES:
        raise CheckError(f"download {url}: larger than {MAX_CRATE_BYTES} bytes")
    if sha256(data) != package.checksum:
        notes.append(f"downloaded {url}: checksum differs from Cargo.lock")
        return None
    return data


def zed_origin(manifest, package):
    """(zed-crate, zed-rev, problems) from a published manifest."""
    problems = []
    info = manifest.get("package")
    if not isinstance(info, dict):
        return None, None, ["Cargo.toml has no [package] table"]
    if (info.get("name"), info.get("version")) != (package.name, package.version):
        problems.append(f"Cargo.toml declares {info.get('name')} {info.get('version')}")
    metadata = info.get("metadata")
    origin = metadata.get(METADATA_TABLE) if isinstance(metadata, dict) else None
    if not isinstance(origin, dict):
        return None, None, problems + [f"Cargo.toml has no [package.metadata.{METADATA_TABLE}]"]
    zed_crate, zed_rev = origin.get("zed-crate"), origin.get("zed-rev")
    if not (isinstance(zed_crate, str) and CRATE_NAME.fullmatch(zed_crate)):
        problems.append(f"zed-crate missing or not a crate name: {zed_crate!r}")
        zed_crate = None
    if not (isinstance(zed_rev, str) and REV.fullmatch(zed_rev)):
        problems.append(f"zed-rev missing or not a full commit id: {zed_rev!r}")
        zed_rev = None
    return zed_crate, zed_rev, problems


def build_inputs(manifest):
    """(label, path) of every file the manifest names as a build script or target."""
    inputs = []
    info = manifest.get("package")
    build = info.get("build") if isinstance(info, dict) else None
    for value in build if isinstance(build, list) else [build]:
        if not isinstance(value, bool) and value is not None:
            inputs.append(("package.build", value))
    for table in TARGET_TABLES:
        targets = manifest.get(table)
        for target in targets if isinstance(targets, list) else [targets]:
            if isinstance(target, dict) and "path" in target:
                inputs.append((f"[{table}] path", target["path"]))
    return inputs


def check_build_inputs(manifest, files):
    """A target may only name a shipped file that is compared with Zed."""
    problems = []
    for label, path in build_inputs(manifest):
        normal = posixpath.normpath(path) if isinstance(path, str) else None
        if normal not in files or normal in PACKAGING_FILES:
            problems.append(f"{label} = {path!r} is not a file compared with Zed")
    return problems


def inspect_crate(package, cargo_home, download):
    report = PackageReport(package)
    notes = report.problems
    if package.source != CRATES_IO:
        notes.append(f"source {package.source!r} is not crates.io")
        return report
    if not (isinstance(package.checksum, str) and SHA256.fullmatch(package.checksum)):
        notes.append("Cargo.lock has no SHA-256 checksum")
        return report
    skipped = []
    data = crate_archive(package, cargo_home, download, skipped)
    if data is None:
        notes.extend(skipped)
        return report
    try:
        files = read_crate_archive(data, package.name, package.version)
        manifest = parse_toml(files["Cargo.toml"].decode("utf-8"))
    except KeyError:
        notes.append("archive has no Cargo.toml")
        return report
    except (ValueError, UnicodeDecodeError) as error:
        notes.append(f"invalid package: {error}")
        return report
    report.files = files
    reference = RENAMED_CRATES.get((package.name, package.version))
    if reference is not None:
        info = manifest.get("package", {})
        if (info.get("name"), info.get("version")) != (package.name, package.version):
            notes.append("Cargo.toml package identity differs from Cargo.lock")
        notes.extend(check_build_inputs(manifest, files))
        compare_registry_source(report, reference, cargo_home, download)
        return report
    report.zed_crate, report.zed_rev, problems = zed_origin(manifest, package)
    notes.extend(problems)
    notes.extend(check_build_inputs(manifest, files))
    return report


def compare_registry_source(report, reference, cargo_home, download):
    """Check every source file of an explicitly registered renamed crate."""
    data = crate_archive(reference, cargo_home, download, report.problems)
    if data is None:
        return
    try:
        upstream = read_crate_archive(data, reference.name, reference.version)
    except ValueError as error:
        report.problems.append(f"invalid reference package: {error}")
        return
    report.zed_dir = f"crates.io/{reference.name}@{reference.version}"
    for path in sorted(report.files.keys() | upstream.keys()):
        if path in PACKAGING_FILES:
            report.ignored.append(path)
        elif report.files.get(path) != upstream.get(path):
            report.problems.append(f"differs from {reference.name}: {path}")
        else:
            report.identical += 1
    report.reviewed.append(f"renamed registry source, checksum {reference.checksum}")


# --- Zed side -----------------------------------------------------------------

def git(repo, *args):
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    try:
        result = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, env=env)
    except OSError as error:
        raise CheckError(f"cannot run git: {error}")
    if result.returncode != 0:
        detail = result.stderr.decode("utf-8", "replace").strip()
        raise GitError(f"git {' '.join(args)} failed: {detail}", result.returncode)
    return result.stdout


def fetch_zed(repo, remote, revs, branch):
    """Fetch the commits with their trees (no blobs) and the recent history of `branch`
    (commits only) into a partial clone; returns the ref holding that branch."""
    repo.mkdir(parents=True, exist_ok=True)
    git(repo, "init", "--quiet")
    remotes = git(repo, "remote").decode().split()
    git(repo, "remote", "set-url" if "zed" in remotes else "add", "zed", remote)
    fetch = ("-c", "protocol.version=2", "-c", "fetch.fsckObjects=true", "fetch", "--quiet", "--no-tags")
    git(repo, *fetch, "--depth=1", "--filter=blob:none", "zed", *revs)
    oldest = min(int(git(repo, "log", "-1", "--format=%ct", rev)) for rev in revs) - HISTORY_MARGIN
    since = time.strftime("%Y-%m-%d %H:%M:%S +0000", time.gmtime(oldest))
    ref = f"refs/remotes/zed/{branch}"
    git(repo, *fetch, "--filter=tree:0", f"--shallow-since={since}", "zed", f"+refs/heads/{branch}:{ref}")
    return ref


def is_ancestor(repo, rev, ref):
    try:
        git(repo, "merge-base", "--is-ancestor", rev, ref)
    except GitError as error:
        if error.returncode == 1:
            return False
        raise
    return True


class ZedTree:
    """All entries of one commit: {path: (mode, type, object id)}, and blob access."""

    def __init__(self, repo, rev, remote=None):
        self.repo = repo
        self.remote = remote  # promisor remote of a partial clone made by fetch_zed
        if git(repo, "cat-file", "-t", rev).strip() != b"commit":
            raise CheckError(f"{rev} is not a commit")
        self.entries = {}
        for record in git(repo, "ls-tree", "-r", "-z", "--full-tree", rev).split(b"\0"):
            if record:
                meta, path = record.split(b"\t", 1)
                mode, kind, oid = meta.decode("ascii").split(" ")
                self.entries[path.decode("utf-8", "surrogateescape")] = (mode, kind, oid)
        self.blobs = {}

    def prefetch(self, oids):
        """Fetch blobs in one request; on demand git would make one request per blob."""
        missing = sorted(set(oids) - set(self.blobs))
        if self.remote and missing:
            git(self.repo, "-c", "fetch.negotiationAlgorithm=noop", "fetch", "--quiet", "--no-tags",
                "--no-write-fetch-head", "--recurse-submodules=no", "--filter=blob:none",
                self.remote, *missing)

    def read_blob(self, oid):
        if oid not in self.blobs:
            self.blobs[oid] = git(self.repo, "cat-file", "blob", oid)
        return self.blobs[oid]


def resolve(tree, path):
    """Blob id of the regular file that `path` is or (through symlinks) points to."""
    for _ in range(MAX_SYMLINK_HOPS):
        entry = tree.entries.get(path)
        if entry is None or entry[1] != "blob":
            raise ValueError(f"{path} is not a file in the Zed tree")
        mode, _, oid = entry
        if mode != "120000":
            return oid
        target = tree.read_blob(oid).decode("utf-8", "surrogateescape")
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(path), target))
        if target.startswith("/") or resolved == ".." or resolved.startswith("../"):
            raise ValueError(f"symlink {path} -> {target} leaves the repository")
        path = resolved
    raise ValueError(f"symlink chain from {path} is too long")


def read_manifest(tree, path):
    entry = tree.entries.get(path)
    if entry is None or entry[:2] != ("100644", "blob"):
        raise ValueError(f"{path} is not a regular file in the Zed tree")
    try:
        return parse_toml(tree.read_blob(entry[2]).decode("utf-8"))
    except (ValueError, UnicodeDecodeError) as error:
        raise ValueError(f"Zed {path}: {error}")


def workspace_members(tree):
    """Package directories listed in the [workspace] members of Zed's root Cargo.toml."""
    if "Cargo.toml" in tree.entries:
        tree.prefetch([tree.entries["Cargo.toml"][2]])
    try:
        workspace = read_manifest(tree, "Cargo.toml").get("workspace")
    except ValueError as error:
        raise CheckError(str(error))
    members = workspace.get("members") if isinstance(workspace, dict) else None
    if not isinstance(members, list) or not all(isinstance(member, str) for member in members):
        raise CheckError("Zed Cargo.toml has no [workspace] members list")
    return [posixpath.normpath(member) for member in members]


def member_candidates(tree, members, zed_crate):
    return [member for member in members
            if posixpath.basename(member) == zed_crate and f"{member}/Cargo.toml" in tree.entries]


def prefetch_crates(tree, members, zed_crates):
    """Fetch, in one request, the manifests and symlinks that comparing these crates reads."""
    wanted = []
    for zed_crate in zed_crates:
        for member in member_candidates(tree, members, zed_crate):
            prefix = member + "/"
            wanted.extend(oid for path, (mode, kind, oid) in tree.entries.items()
                          if path == prefix + "Cargo.toml" or (path.startswith(prefix) and mode == "120000"))
    tree.prefetch(wanted)


def find_crate_dir(tree, members, zed_crate):
    """The only workspace member directory named zed_crate whose package is zed_crate."""
    found = member_candidates(tree, members, zed_crate)
    if len(found) != 1:
        raise ValueError(f"expected one Zed workspace member named {zed_crate}, found {found or 'none'}")
    package = read_manifest(tree, f"{found[0]}/Cargo.toml").get("package")
    name = package.get("name") if isinstance(package, dict) else None
    if name != zed_crate:
        raise ValueError(f"Zed {found[0]}/Cargo.toml is package {name!r}, not {zed_crate}")
    return found[0]


def upstream_files(tree, crate_dir, report):
    """{relative path: blob id} that cargo package would ship from crate_dir."""
    prefix = crate_dir + "/"
    entries = {path[len(prefix):]: entry for path, entry in tree.entries.items()
               if path.startswith(prefix)}
    report.nested = sorted({posixpath.dirname(rel) for rel in entries
                            if "/" in rel and posixpath.basename(rel) == "Cargo.toml"})
    files = {}
    for rel, (mode, kind, oid) in sorted(entries.items()):
        if any(rel.startswith(root + "/") for root in report.nested):
            continue
        if kind != "blob":
            report.problems.append(f"unsupported Zed entry {rel} ({kind})")
            continue
        if mode == "120000":
            try:
                oid = resolve(tree, prefix + rel)
            except ValueError as error:
                report.problems.append(str(error))
                continue
            report.symlinks.append(rel)
        files[rel] = oid
    return files


