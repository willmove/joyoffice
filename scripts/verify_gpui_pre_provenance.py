@contextlib.contextmanager
def zed_repository(args, revs):
    """(repository holding `revs`, its promisor remote or None, ref of the Zed branch, label)."""
    if args.zed_repo:
        git(args.zed_repo, "rev-parse", "--verify", "--quiet", f"{args.zed_branch}^{{commit}}")
        yield args.zed_repo, None, args.zed_branch, str(args.zed_repo)
        return
    with contextlib.ExitStack() as stack:
        repo = args.work_dir or Path(stack.enter_context(tempfile.TemporaryDirectory(prefix="zed-")))
        ref = fetch_zed(repo, args.zed_remote, revs, args.zed_branch)
        yield repo, "zed", ref, args.zed_remote


def print_report(reports, problems, label, branch, timing):
    revs = sorted({report.zed_rev for report in reports if report.zed_rev})
    print(f"gpui-pre provenance: {len(reports)} packages in Cargo.lock, Zed {', '.join(revs) or '?'}")
    print(f"  Zed source: {label}" + (f" (commit must be an ancestor of {branch})" if revs else ""))
    for report in reports:
        status = "FAIL" if report.problems else "reviewed" if report.reviewed else "ok"
        package = report.package
        details = [f"{report.identical} files identical"]
        if report.reviewed:
            details.append(f"{len(report.reviewed)} reviewed deviations")
        if report.symlinks:
            details.append(f"symlinks resolved: {', '.join(report.symlinks)}")
        if report.nested:
            details.append(f"nested packages left out: {', '.join(report.nested)}")
        if report.ignored:
            details.append(f"not compared: {', '.join(report.ignored)}")
        print(f"{status:<8} {package.name} {package.version} = {report.zed_dir or '?'}: {'; '.join(details)}")
        for line in report.reviewed + report.problems:
            print(f"           {line}")
    print("Not compared (cargo packaging output, never accepted as a build target):")
    for name, reason in PACKAGING_FILES.items():
        print(f"  {name}: {reason}")
    print("Upstream normalization:")
    for name, reason in UPSTREAM_RULES.items():
        print(f"  {name}: {reason}")
    for problem in problems:
        print(f"FAIL     {problem}")
    failed = [report for report in reports if report.problems]
    reviewed = [report for report in reports if report.reviewed and not report.problems]
    verdict = "FAILED" if failed or problems else "OK"
    print(f"Result: {verdict}, {len(reports) - len(failed) - len(reviewed)} identical, {len(reviewed)} accepted "
          f"with reviewed deviations, {len(failed)} failed ({timing})")


def parse_args(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lockfile", type=Path, default=ROOT / "Cargo.lock")
    parser.add_argument("--cargo-home", type=Path,
                        default=Path(os.environ.get("CARGO_HOME") or Path.home() / ".cargo"),
                        help="look for cached .crate files under <dir>/registry/cache (default: $CARGO_HOME or ~/.cargo)")
    parser.add_argument("--no-download", action="store_true",
                        help="fail instead of downloading .crate files missing from the Cargo cache")
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--zed-repo", type=Path,
                        help="existing local git repository that contains the Zed commit; nothing is fetched")
    source.add_argument("--zed-remote", default=ZED_REMOTE,
                        help="git URL to fetch the Zed commit from (default: %(default)s)")
    parser.add_argument("--zed-branch", default="main",
                        help="Zed branch every commit must belong to; with --zed-repo any local ref name "
                             "(default: %(default)s)")
    parser.add_argument("--work-dir", type=Path,
                        help="keep the partial Zed clone here (reused on later runs) instead of a temporary directory")
    parser.add_argument("--expected-zed-rev", help="also fail unless every package declares this Zed commit")
    parser.add_argument("--reviewed-deviations", type=Path,
                        help="JSON file of reviewed differences, each pinned to its exact content")
    args = parser.parse_args(argv)
    if args.zed_repo and args.work_dir:
        parser.error("--work-dir has no effect with --zed-repo")
    return args


def run(args):
    started = time.monotonic()
    try:
        lock_text = args.lockfile.read_text(encoding="utf-8")
    except OSError as error:
        raise CheckError(f"{args.lockfile}: {error}")
    try:
        packages = locked_packages(lock_text)
    except ValueError as error:
        raise CheckError(f"{args.lockfile}: {error}")
    if not packages:
        raise CheckError(f"{args.lockfile}: no {PACKAGE_PREFIX} packages")
    deviations = load_deviations(args.reviewed_deviations) if args.reviewed_deviations else {}
    with ThreadPoolExecutor(max_workers=8) as pool:  # downloads dominate when the cache is cold
        reports = list(pool.map(lambda package: inspect_crate(package, args.cargo_home, not args.no_download),
                                packages))
    unpacked = time.monotonic()
    problems = []
    revs = sorted({report.zed_rev for report in reports if report.zed_rev})
    if len(revs) > 1:
        problems.append(f"packages declare different Zed commits: {', '.join(revs)}")
    if args.expected_zed_rev:
        for report in reports:
            if report.zed_rev and report.zed_rev != args.expected_zed_rev:
                report.problems.append(f"zed-rev {report.zed_rev} is not the expected {args.expected_zed_rev}")
    label = "not needed"
    if revs:
        ready = [report for report in reports if report.files is not None and report.zed_crate and report.zed_rev]
        with zed_repository(args, revs) as (repo, remote, branch, label):
            for rev in revs:
                if not is_ancestor(repo, rev, branch):
                    searched = f" (fetched from {HISTORY_MARGIN // 86400} days before it)" if remote else ""
                    problems.append(f"Zed commit {rev} is not in the history of {branch}{searched}")
                tree = ZedTree(repo, rev, remote)
                members = workspace_members(tree)
                batch = [report for report in ready if report.zed_rev == rev]
                prefetch_crates(tree, members, {report.zed_crate for report in batch})
                for report in batch:
                    compare(report, tree, members, deviations)
    for key in sorted(deviations):
        problems.append(f"reviewed deviation matched nothing: {' '.join(key)}")
    finished = time.monotonic()
    print_report(reports, problems, label, args.zed_branch,
                 f"packages {unpacked - started:.1f} s, Zed {finished - unpacked:.1f} s")
    return 1 if problems or any(report.problems for report in reports) else 0


def main(argv=None):
    try:
        return run(parse_args(argv))
    except CheckError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
