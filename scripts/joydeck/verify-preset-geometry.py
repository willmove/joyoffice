#!/usr/bin/env python3
"""Render an original public PPTX with either baseline or updated JoyDeck CLI."""
import argparse
import hashlib
import json
import subprocess
import zipfile
from pathlib import Path
from xml.sax.saxutils import escape

PRESETS = [
    "triangle", "diamond", "pentagon", "hexagon", "star5", "heart",
    "leftArrow", "leftRightArrow", "chevron", "parallelogram", "trapezoid", "donut",
    "flowChartDecision", "flowChartDocument", "cloud", "sun", "moon", "lightningBolt",
]
A = "http://schemas.openxmlformats.org/drawingml/2006/main"
P = "http://schemas.openxmlformats.org/presentationml/2006/main"
R = "http://schemas.openxmlformats.org/officeDocument/2006/relationships"


def fixture(path):
    def text(i, value, x, y, w, h, size):
        return f'<p:sp><p:nvSpPr><p:cNvPr id="{i}" name="Label {i}"/><p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr><p:spPr><a:xfrm><a:off x="{x*12700}" y="{y*12700}"/><a:ext cx="{w*12700}" cy="{h*12700}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/></p:spPr><p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr sz="{size*100}"><a:solidFill><a:srgbClr val="202B3A"/></a:solidFill></a:rPr><a:t>{escape(value)}</a:t></a:r></a:p></p:txBody></p:sp>'

    shapes = [text(2, "Preset geometry | One original PPTX", 28, 12, 900, 32, 24)]
    colors = ["129B8C", "3279B8", "A360AD"]
    for i, name in enumerate(PRESETS):
        x, y = 30 + (i % 6) * 154, 60 + (i // 6) * 151
        shapes.append(f'<p:sp><p:nvSpPr><p:cNvPr id="{10+i}" name="{name}"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr><p:spPr><a:xfrm><a:off x="{x*12700}" y="{y*12700}"/><a:ext cx="{118*12700}" cy="{91*12700}"/></a:xfrm><a:prstGeom prst="{name}"><a:avLst/></a:prstGeom><a:solidFill><a:srgbClr val="{colors[i//6]}"/></a:solidFill></p:spPr></p:sp>')
        shapes.append(text(40+i, name, x, y+100, 146, 27, 12))
    group = '<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr><p:grpSpPr/>'
    rels = 'http://schemas.openxmlformats.org/package/2006/relationships'
    parts = {
        '[Content_Types].xml': '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/><Override PartName="/ppt/slides/slide1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/></Types>',
        '_rels/.rels': f'<Relationships xmlns="{rels}"><Relationship Id="main" Type="{R}/officeDocument" Target="ppt/presentation.xml"/></Relationships>',
        'ppt/presentation.xml': f'<p:presentation xmlns:p="{P}" xmlns:r="{R}"><p:sldIdLst><p:sldId id="256" r:id="s1"/></p:sldIdLst><p:sldSz cx="{960*12700}" cy="{540*12700}"/></p:presentation>',
        'ppt/_rels/presentation.xml.rels': f'<Relationships xmlns="{rels}"><Relationship Id="s1" Type="{R}/slide" Target="slides/slide1.xml"/></Relationships>',
        'ppt/slides/slide1.xml': f'<p:sld xmlns:p="{P}" xmlns:a="{A}" xmlns:r="{R}"><p:cSld><p:spTree>{group}{"".join(shapes)}</p:spTree></p:cSld></p:sld>',
        'ppt/slides/_rels/slide1.xml.rels': f'<Relationships xmlns="{rels}"/>',
    }
    with zipfile.ZipFile(path, 'w', zipfile.ZIP_DEFLATED) as package:
        for name, content in parts.items():
            info = zipfile.ZipInfo(name, (2026, 11, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            package.writestr(info, content.encode())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cli', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    source = output / 'presets.pptx'
    fixture(source)
    base = [str(args.cli.resolve()), '--read-root', str(output), '--write-root', str(output)]
    for command, parameters in [('inspect', [str(source)]), ('render', [str(source), str(output / 'render.png'), 'png'])]:
        result = subprocess.run(base + [command] + parameters, text=True, encoding='utf-8', capture_output=True, check=True)
        (output / f'{command}.json').write_text(result.stdout, encoding='utf-8')
    (output / 'fixture.json').write_text(json.dumps({'origin': 'Original synthetic DrawingML fixture; generated by this script, no external artwork', 'presets': PRESETS, 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'cliSha256': hashlib.sha256(args.cli.read_bytes()).hexdigest()}, indent=2) + '\n', encoding='utf-8')
    print(output)


if __name__ == '__main__':
    main()
