"""Build original Chinese gallery templates (requires python-docx 1.2.0).

Run from any directory. DOCX ZIP metadata and core properties are fixed so
re-running with the same python-docx version produces identical bytes.
Use --cli PATH to refresh first-page thumbnails with the JoyWord renderer.
System fonts are referenced by name only and are never copied into the repo.
"""

