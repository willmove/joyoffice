def element(name: str, **attrs):
    node = OxmlElement(f"w:{name}")
    for key, value in attrs.items():
        node.set(qn(f"w:{key}"), str(value))
    return node


def font(style, size: float, bold: bool = False):
    style.font.name = "Arial"
    style.font.size = Pt(size)
    style.font.bold = bold
    style.font.italic = False
    style.font.color.rgb = RGBColor(0, 0, 0)
    fonts = style.element.get_or_add_rPr().rFonts
    fonts.set(qn("w:eastAsia"), "Microsoft YaHei")
    # Explicit names should take precedence over python-docx's default theme.
    for key in ("asciiTheme", "hAnsiTheme", "eastAsiaTheme", "cstheme"):
        fonts.attrib.pop(qn(f"w:{key}"), None)


def document(title: str, subtitle: str, intro: str):
    doc = Document()
    section = doc.sections[0]
    section.page_width, section.page_height = Mm(210), Mm(297)
    section.top_margin = section.bottom_margin = Mm(20)
    section.left_margin = section.right_margin = Mm(22)
    for name, size, bold in (("Normal", 10.5, False), ("Title", 22, True),
                             ("Subtitle", 10, False), ("Heading 1", 13, True),
                             ("Heading 2", 11, True)):
        style = doc.styles[name]
        font(style, size, bold)
        style.paragraph_format.line_spacing = 1.15
        style.paragraph_format.space_after = Pt(5)
        borders = style.element.get_or_add_pPr().find(qn("w:pBdr"))
        if borders is not None:
            style.element.pPr.remove(borders)
    doc.styles["Normal"].paragraph_format.widow_control = True
    doc.styles["Title"].paragraph_format.space_after = Pt(8)
    for name in ("Heading 1", "Heading 2"):
        doc.styles[name].paragraph_format.space_before = Pt(8)
        doc.styles[name].paragraph_format.keep_with_next = True
    props = doc.core_properties
    props.title, props.subject = title, subtitle
    props.author = props.last_modified_by = "JoyOffice"
    props.created = props.modified = datetime(2026, 11, 17, tzinfo=timezone.utc)
    props.revision = 1
    props.language = "zh-CN"
    doc.add_paragraph(title, "Title")
    doc.add_paragraph(subtitle, "Subtitle")
    doc.add_paragraph(intro)
    return doc


def section(doc, title: str, *paragraphs: str):
    doc.add_paragraph(title, "Heading 1")
    for text in paragraphs:
        doc.add_paragraph(text)


def table(doc, headers, rows, widths, centered=()):
    grid = doc.add_table(rows=1, cols=len(headers))
    grid.autofit = False
    for column, width in zip(grid.columns, widths, strict=True):
        column.width = Mm(width)
    borders = element("tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        borders.append(element(side, val="single", sz=4, color="D9D9D9"))
    grid._tbl.tblPr.append(borders)
    margins = element("tblCellMar")
    for side, value in (("top", 80), ("bottom", 80), ("left", 100), ("right", 100)):
        margins.append(element(side, w=value, type="dxa"))
    grid._tbl.tblPr.append(margins)
    grid.rows[0]._tr.get_or_add_trPr().append(element("tblHeader"))
    for row_index, values in enumerate((headers, *rows)):
        row = grid.rows[0] if row_index == 0 else grid.add_row()
        row._tr.get_or_add_trPr().append(element("cantSplit"))
        for col, (cell, text, width) in enumerate(zip(row.cells, values, widths, strict=True)):
            cell.width = Mm(width)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            cell._tc.get_or_add_tcPr().append(element("shd", fill="E8EFF8" if row_index == 0 else "FFFFFF"))
            paragraph = cell.paragraphs[0]
            paragraph.paragraph_format.space_after = Pt(0)
            paragraph.paragraph_format.line_spacing = 1.15
            if col in centered:
                paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
            run = paragraph.add_run(text)
            run.font.size = Pt(9.5)
            run.bold = row_index == 0


