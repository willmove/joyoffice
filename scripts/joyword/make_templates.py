def save(doc, path: Path):
    buffer = BytesIO()
    doc.save(buffer)
    with zipfile.ZipFile(buffer) as source, zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as output:
        for name in sorted(source.namelist()):
            info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            output.writestr(info, source.read(name))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", type=Path, help="JoyWord CLI executable for gallery previews")
    args = parser.parse_args()
    for name, build in zip(NAMES, (project_plan, meeting_minutes, weekly_report, notice, study_notes), strict=True):
        save(build(), SAMPLES / f"{name}.docx")
    if args.cli:
        cli = args.cli.resolve()
        with tempfile.TemporaryDirectory(prefix="joyword-template-previews-") as staging:
            for name in NAMES:
                output = Path(staging) / f"{name}.png"
                subprocess.run([str(cli), "render", str(SAMPLES / f"{name}.docx"), str(output),
                                "--page", "1", "--scale", "0.5"], check=True)
                (SAMPLES / "previews" / output.name).write_bytes(output.read_bytes())
    registry = SAMPLES / "SOURCE.json"
    registry_bytes = registry.read_bytes()
    newline = "\r\n" if b"\r\n" in registry_bytes else "\n"
    sources = json.loads(registry_bytes)
    updated = {f"{name}.docx": ORIGIN for name in NAMES}
    if args.cli:
        updated.update({f"previews/{name}.png": f"First page of {name}.docx rendered by JoyWord CLI at 0.5 px per point"
                        for name in NAMES})
    entries = {entry["file"]: entry for entry in sources}
    for name, origin in updated.items():
        entry = {"file": name, "sha256": hashlib.sha256((SAMPLES / name).read_bytes()).hexdigest(),
                 "source": origin}
        if name in entries:
            entries[name].update(entry)
        else:
            sources.append(entry)
    registry.write_bytes((json.dumps(sources, ensure_ascii=False, indent=2) + "\n").replace("\n", newline).encode("utf-8"))


if __name__ == "__main__":
    main()
