//! Embed language dictionaries, hyphenation patterns and licence notices from
//! the vendored `third-party/craft-i18n/language-data/` directory or an explicit
//! `CRAFT_I18N_DIR` checkout.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const FILES: &[(&str, &str, bool)] = &[
    ("EN_US_DIC", "en-us/en-us.dic", true),
    ("EN_US_AFF", "en-us/spelling.aff", false),
    ("EN_US_SPELLING", "en-us/spelling.dic", false),
    ("EN_GB_AFF", "en-gb/spelling.aff", false),
    ("EN_GB_SPELLING", "en-gb/spelling.dic", false),
    ("EN_CA_AFF", "en-ca/spelling.aff", false),
    ("EN_CA_SPELLING", "en-ca/spelling.dic", false),
    ("EN_AU_AFF", "en-au/spelling.aff", false),
    ("EN_AU_SPELLING", "en-au/spelling.dic", false),
    ("SCOWL_NOTICE", "en-us/LICENCE-SCOWL.txt", false),
    ("EN_US_PAT", "en-us/hyphenation.pat", false),
    ("EXTRA_EN", "en-us/en-extra.txt", false),
    ("EN_VARIANTS", "en-us/en-variants.txt", false),
    ("PL_PAT", "pl/hyphenation.pat", false),
    ("PT_PAT", "pt/hyphenation.pat", false),
    ("IT_PAT", "it/hyphenation.pat", false),
    ("DE_PAT", "de/hyphenation.pat", false),
    ("EXTRA_RU", "ru/ru-extra.txt", false),
];

const DEFAULT_EMBED: &[&str] = &["de", "pl", "pt", "it", "ru"];

fn opted_in() -> Vec<String> {
    let raw = std::env::var("CRAFT_PROOF_EMBED").unwrap_or_default();
    let named: Vec<String> = raw
        .split(',')
        .map(|l| l.trim().to_ascii_lowercase())
        .filter(|l| !l.is_empty())
        .collect();
    if named.is_empty() {
        DEFAULT_EMBED.iter().map(|l| (*l).to_owned()).collect()
    } else {
        named
    }
}

fn is_supplement(rel: &str) -> bool {
    rel.ends_with("-extra.txt")
}

fn should_embed(rel: &str, locale: &str, opted: &[String]) -> bool {
    is_supplement(rel)
        || locale.starts_with("en-")
        || opted.iter().any(|o| o == locale || o == "all")
}

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    println!("cargo::rerun-if-env-changed=CRAFT_I18N_DIR");
    println!("cargo::rerun-if-env-changed=CRAFT_I18N_REQUIRED");
    println!("cargo::rerun-if-env-changed=CRAFT_PROOF_EMBED");
    println!("cargo::rustc-check-cfg=cfg(craft_proof_data)");
    println!("cargo::rustc-check-cfg=cfg(craft_proof_no_data)");
    println!(
        "cargo::rustc-check-cfg=cfg(craft_proof_embed, values(\"pl\", \"pt\", \"it\", \"de\", \"ru\"))"
    );

    let opted = opted_in();
    let required = std::env::var("CRAFT_I18N_REQUIRED").is_ok_and(|v| v.trim() == "1");
    let level = if required { "error" } else { "warning" };
    let vendored = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../third-party/craft-i18n");
    println!("cargo::rerun-if-changed={}", vendored.display());

    let input = std::env::var_os("CRAFT_I18N_DIR")
        .filter(|d| !d.is_empty())
        .or_else(|| vendored.is_dir().then(|| vendored.into_os_string()));
    let dir = match input {
        Some(d) => match resolve_language_data(&PathBuf::from(d)) {
            Ok(data_dir) => Some(data_dir),
            Err(err) => {
                println!(
                    "cargo::{level}=CRAFT_I18N_DIR: {err}; joyword-proof embeds no language data"
                );
                None
            }
        },
        None => {
            if required {
                println!(
                    "cargo::error=CRAFT_I18N_REQUIRED=1 but language-data directory is missing"
                );
            } else {
                println!(
                    "cargo::warning=CRAFT_I18N_DIR is unset and vendored language-data is absent"
                );
            }
            None
        }
    };

    let mut generated =
        String::from("// Generated by joyword-proof build.rs from language-data. Do not edit.\n");
    let (mut wanted_count, mut embedded_count) = (0usize, 0usize);
    let mut locales = Vec::new();
    for &(const_name, rel, is_bytes) in FILES {
        let locale = rel.split('/').next().unwrap_or_default();
        let wanted = should_embed(rel, locale, &opted);
        wanted_count += usize::from(wanted);
        let file = dir
            .as_ref()
            .filter(|_| wanted)
            .map(|d| d.join(rel))
            .filter(|f| f.is_file());
        if let (Some(d), None, true) = (&dir, &file, wanted) {
            println!(
                "cargo::{level}=CRAFT_I18N_DIR: {} is missing",
                d.join(rel).display()
            );
        }
        let (ty, empty, macro_name) = if is_bytes {
            ("&[u8]", "b\"\"", "include_bytes")
        } else {
            ("&str", "\"\"", "include_str")
        };
        let value = match file.as_ref().and_then(|f| f.to_str()) {
            Some(path_str) => {
                println!("cargo::rerun-if-changed={path_str}");
                embedded_count += 1;
                if !locale.starts_with("en-") {
                    println!("cargo::rustc-cfg=craft_proof_embed=\"{locale}\"");
                }
                if !is_supplement(rel) && !locales.iter().any(|l| l == locale) {
                    locales.push(locale.to_owned());
                }
                format!("{macro_name}!({path_str:?})")
            }
            None => empty.to_owned(),
        };
        let _ = writeln!(generated, "pub(crate) static {const_name}: {ty} = {value};");
    }

    if embedded_count > 0 && embedded_count == wanted_count {
        println!("cargo::rustc-cfg=craft_proof_data");
    } else if embedded_count == 0 {
        println!("cargo::rustc-cfg=craft_proof_no_data");
    }

    let _ = writeln!(
        generated,
        "pub(crate) static EMBEDDED_LOCALES: &[&str] = &{locales:?};"
    );

    let mut licences = String::new();
    if let Some(d) = &dir {
        for locale in &locales {
            let mut files: Vec<PathBuf> = std::fs::read_dir(d.join(locale))
                .into_iter()
                .flatten()
                .filter_map(Result::ok)
                .map(|e| e.path())
                .filter(|p| {
                    p.is_file()
                        && p.file_name().is_some_and(|n| {
                            n.to_string_lossy()
                                .to_ascii_uppercase()
                                .starts_with("LICENCE")
                        })
                })
                .collect();
            files.sort();
            for f in files {
                println!("cargo::rerun-if-changed={}", f.display());
                let Some(path) = f.to_str() else {
                    println!(
                        "cargo::{level}=CRAFT_I18N_DIR: {} is not UTF-8; licence text skipped",
                        f.display()
                    );
                    continue;
                };
                if let Err(err) = std::fs::read_to_string(&f) {
                    println!(
                        "cargo::{level}=CRAFT_I18N_DIR: {path} cannot be read as UTF-8 ({err})"
                    );
                    continue;
                }
                let title = format!(
                    "{locale}: {}",
                    f.file_name()
                        .map(|n| n.to_string_lossy().into_owned())
                        .unwrap_or_default()
                );
                let _ = write!(licences, "({title:?}, include_str!({path:?})), ");
            }
        }
    }
    let _ = writeln!(
        generated,
        "pub(crate) static EMBEDDED_LICENCES: &[(&str, &str)] = &[{licences}];"
    );

    let out =
        PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default()).join("language_data.rs");
    if let Err(err) = std::fs::write(&out, generated) {
        println!("cargo::error=writing {}: {err}", out.display());
    }
}

fn resolve_language_data(dir: &Path) -> Result<PathBuf, String> {
    if !dir.is_absolute() {
        return Err(format!("{} is not an absolute path", dir.display()));
    }
    if dir.to_str().is_none() {
        return Err(format!("{} is not valid UTF-8", dir.display()));
    }
    let data = dir.join("language-data");
    if !data.is_dir() {
        println!("cargo::rerun-if-changed={}", dir.display());
        return Err(format!("{} has no language-data/", dir.display()));
    }
    println!("cargo::rerun-if-changed={}", data.display());
    Ok(data)
}
