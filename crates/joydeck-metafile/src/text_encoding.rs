//! Byte-to-scalar projection for Windows metafile text.
//! Tables are derived from Unicode's published Microsoft CP1250/1251/1252 mappings.

use crate::text::SYMBOL_CHARSET;

fn project(
    characters: impl IntoIterator<Item = (char, usize)>,
    advances: &[f32],
) -> (String, Vec<f32>) {
    let mut text = String::new();
    let mut projected = Vec::new();
    let mut position: usize = 0;
    for (character, width) in characters {
        text.push(character);
        if !advances.is_empty() {
            let end = position + width;
            let start = position.min(advances.len());
            projected.push(advances[start..end.min(advances.len())].iter().sum());
            position = end;
        }
    }
    (text, projected)
}

pub(crate) fn decode_utf16(units: &[u16], advances: &[f32]) -> (String, Vec<f32>) {
    let characters = char::decode_utf16(units.iter().copied()).map(|value| {
        let character = value.unwrap_or(char::REPLACEMENT_CHARACTER);
        (character, character.len_utf16())
    });
    project(characters, advances)
}

pub(crate) fn decode_bytes(mut bytes: &[u8], charset: u8, advances: &[f32]) -> (String, Vec<f32>) {
    let dbcs = matches!(charset, 128 | 129 | 130 | 134 | 136);
    let table = match charset {
        238 => &CP1250,
        204 => &CP1251,
        _ => &CP1252,
    };
    let characters = std::iter::from_fn(move || {
        let (&byte, rest) = bytes.split_first()?;
        bytes = rest;
        if dbcs
            && byte >= 0x81
            && let Some((_, rest)) = bytes.split_first()
        {
            bytes = rest;
            return Some((' ', 2));
        }
        let value = match (charset, byte) {
            (SYMBOL_CHARSET, byte) => 0xf000 + u32::from(byte),
            (_, 0..=127) => u32::from(byte),
            (_, byte) => u32::from(table[usize::from(byte - 128)]),
        };
        let character = if value == 0 && byte >= 128 {
            char::REPLACEMENT_CHARACTER
        } else {
            char::from_u32(value).unwrap_or(char::REPLACEMENT_CHARACTER)
        };
        Some((character, 1))
    });
    project(characters, advances)
}

