#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn symbol_bullet_and_wingdings_shapes_follow_the_published_bytes() {
        assert_eq!(map_private_use("Symbol", "\u{F0B7}"), "\u{2022}");
        assert_eq!(map_private_use("symbol", "\u{F0B7}x"), "\u{2022}x");
        assert_eq!(map_private_use("Wingdings", "\u{F06C}"), "\u{26AB}");
        assert_eq!(map_private_use("WINGDINGS", "\u{F09F}"), "\u{2022}");
        assert_eq!(map_private_use("Wingdings", "\u{F0A7}"), "\u{25AA}");
        assert_eq!(map_private_use("Wingdings", "\u{F0B7}"), "\u{1F550}");
        assert_eq!(map_private_use("Times New Roman", "\u{F0B7}"), "\u{F0B7}");
        assert_eq!(map_private_use("Symbol", "\u{F060}"), "\u{F060}");
        assert!(!is_mapped_family("Wingdings 2"));
    }
}
