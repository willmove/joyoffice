//! Symbol and Wingdings private-use labels (ECMA-376 level `w:rFonts`).
//!
//! Word stores those fonts' glyphs as Unicode private-use characters
//! U+F020..=U+F0FF. The low byte is the font encoding. This module maps
//! that byte through published encoding tables and leaves every other
//! character unchanged. It does not select a font face.
//!
//! Symbol bytes follow the Unicode Consortium's Adobe Symbol encoding
//! table (2011-07-12), first non-private-use assignment per byte:
//! <https://www.unicode.org/Public/MAPPINGS/VENDORS/ADOBE/symbol.txt>.
//! Corporate-use assignments with no other Unicode scalar stay unmapped.
//!
//! Wingdings bytes follow the source-reference pairs in Michel Suignard,
//! "Wingdings and Webdings symbols" (Unicode L2/11-344, WG2 N4363),
//! section 7. A Wingdings index `w-1xxx` uses byte `xxx - 1000`
//! (indexes 1033..=1254, skipping 1127). Wingdings 2, Wingdings 3 and
//! Webdings are not mapped.

/// `true` when `name` is the Symbol or Wingdings family, ASCII case-insensitive.
pub fn is_mapped_family(name: &str) -> bool {
    name.eq_ignore_ascii_case("Symbol") || name.eq_ignore_ascii_case("Wingdings")
}

/// Map PUA label characters when `name` is Symbol or Wingdings.
/// Other families and unmapped bytes are copied unchanged.
pub fn map_private_use(name: &str, text: &str) -> String {
    let table = if name.eq_ignore_ascii_case("Symbol") {
        &SYMBOL
    } else if name.eq_ignore_ascii_case("Wingdings") {
        &WINGDINGS
    } else {
        return text.to_owned();
    };
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        let code = ch as u32;
        if (0xF020..=0xF0FF).contains(&code) {
            let mapped = table[(code & 0xFF) as usize];
            if let Some(mapped) = char::from_u32(mapped).filter(|_| mapped != 0) {
                out.push(mapped);
                continue;
            }
        }
        out.push(ch);
    }
    out
}

